import { expect, test } from "@playwright/test";
import { createHash, createHmac } from "node:crypto";

test.skip(process.env.CASPRA_E2E_REAL !== "1", "Enable the disposable real API with CASPRA_E2E_REAL=1");

test("cashier funds a customer, closes the shift, and enrolls the customer portal", async ({ page, request }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const login = await request.post("/admin/api/v1/auth/login", { data: { email: "owner@pilot.test", password: "browser-test-password" } });
  expect(login.ok()).toBeTruthy();
  const token = (await login.json()).access_token;
  const headers = { Authorization: `Bearer ${token}` };
  const suffix = crypto.randomUUID().slice(0, 8);
  const playerName = `Pilot player ${suffix}`;
  const created = await request.post("/admin/api/v1/customers", { headers, data: { full_name: playerName, email: `player-${suffix}@example.test` } });
  expect(created.status()).toBe(201);
  const customer = await created.json();
  const card = await request.post("/admin/api/v1/cards", { headers, data: { uid: `CARD-${suffix}`, customer_id: customer.id, type: "rfid" } });
  expect(card.status()).toBe(201);

  await page.goto("/");
  await page.getByLabel("Email").fill("owner@pilot.test");
  await page.getByLabel("Password").fill("browser-test-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Operations overview" })).toBeVisible();
  const menu = page.getByRole("button", { name: "Open navigation" });
  if (await menu.isVisible()) await menu.click();
  await page.getByRole("link", { name: "Cashier shifts", exact: true }).click();
  await page.getByRole("button", { name: "Open shift", exact: true }).click();
  await page.getByLabel("Terminal name").fill(`desk-${suffix}`);
  await page.getByLabel("Opening cash").fill("10.00");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  const shift = page.getByRole("row").filter({ hasText: `desk-${suffix}` });
  await shift.getByRole("button", { name: "Cash top-up" }).click();
  await page.getByLabel("Customer", { exact: true }).selectOption({ label: playerName });
  await page.getByLabel("Custom amount (leave blank for package)").fill("25.00");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "paid +" })).toContainText("$25.00");
  await shift.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByLabel("Counted cash").fill("35.00");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(shift).toContainText("$0.00");
  await page.screenshot({ path: testInfo.outputPath("cashier-real-api.png"), fullPage: true });

  await page.goto(`/customers/${customer.id}`);
  await page.getByRole("button", { name: "Issue portal link" }).click();
  await page.getByRole("button", { name: "Save", exact: true }).click();
  const invitation = await page.locator('a[href*="/portal#invite="]').getAttribute("href");
  expect(invitation).toBeTruthy();
  await page.goto(invitation!);
  await page.getByLabel("Password", { exact: true }).fill("customer-test-password");
  await page.getByRole("button", { name: "Activate account", exact: true }).click();
  await expect(page.getByRole("heading", { name: playerName })).toBeVisible();
  await expect(page.getByText("Online top-ups are unavailable.", { exact: false })).toBeVisible();
  await expect(page.getByText("$25.00", { exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "Report lost card" }).click();
  await page.getByLabel("Type BLOCK to confirm").fill("BLOCK");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText(`CARD-${suffix} · lost`)).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("portal-real-api.png"), fullPage: true });
  expect(errors).toEqual([]);
});

test("owner provisions machine pricing and resolves an uncertain reader play", async ({ page, request }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.getByLabel("Email").fill("owner@pilot.test");
  await page.getByLabel("Password").fill("browser-test-password");
  const loginResponse = page.waitForResponse(response => response.url().endsWith("/auth/login") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  const token = (await (await loginResponse).json()).access_token;
  let headers = { Authorization: `Bearer ${token}` };
  const suffix = crypto.randomUUID().slice(0, 8);
  await page.goto("/devices");
  await page.getByRole("button", { name: "Register reader", exact: true }).click();
  await page.getByLabel("Reader name", { exact: true }).fill(`Reader ${suffix}`);
  const readerResponse = page.waitForResponse(response => response.url().endsWith("/devices") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  const reader = await (await readerResponse).json();
  await page.getByRole("button", { name: "Dismiss credentials" }).click();
  await page.goto("/machines");
  await page.getByRole("button", { name: "Add machine", exact: true }).click();
  await page.getByLabel("Machine name", { exact: true }).fill(`Racer ${suffix}`);
  await page.getByLabel("Reader", { exact: true }).selectOption({ label: `Reader ${suffix}` });
  await page.getByLabel("Price per play", { exact: true }).fill("2.50");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("row").filter({ hasText: `Racer ${suffix}` })).toContainText("$2.50");

  const fixtureLogin = await request.post("/admin/api/v1/auth/login", { data: { email: "owner@pilot.test", password: "browser-test-password" } });
  expect(fixtureLogin.ok()).toBeTruthy();
  headers = { Authorization: `Bearer ${(await fixtureLogin.json()).access_token}` };
  const created = await request.post("/admin/api/v1/customers", { headers, data: { full_name: `Racer player ${suffix}` } });
  expect(created.status()).toBe(201);
  const customer = await created.json();
  const cardUid = `RACER-${suffix}`;
  expect((await request.post("/admin/api/v1/cards", { headers, data: { uid: cardUid, type: "rfid", customer_id: customer.id } })).status()).toBe(201);
  const wallet = await request.post("/admin/api/v1/wallets", { headers, data: { customer_id: customer.id, type: "credit", currency: "USD" } });
  expect(wallet.status()).toBe(201);
  const walletId = (await wallet.json()).id;
  expect((await request.post(`/admin/api/v1/wallets/${walletId}/topup`, { headers, data: { amount_minor: 1000, currency: "USD", idempotency_key: crypto.randomUUID() } })).status()).toBe(200);

  async function readerPost(path: string, data: unknown) {
    const body = JSON.stringify(data);
    const at = String(Math.floor(Date.now() / 1000));
    const nonce = crypto.randomUUID();
    const hash = createHash("sha256").update(body).digest("hex");
    const signature = createHmac("sha256", reader.hmac_secret).update(`POST\n${path}\n${reader.id}\n${at}\n${nonce}\n${hash}`).digest("hex");
    const response = await request.post(`http://127.0.0.1:18005${path}`, { data: body, headers: { "Content-Type": "application/json", "X-Device-Id": reader.id, "X-Device-Timestamp": at, "X-Device-Nonce": nonce, "X-Device-Signature-Version": "2", "X-Device-Signature": signature } });
    expect(response.ok(), await response.text()).toBeTruthy();
    return response.json();
  }
  const play = await readerPost("/device/api/v1/plays", { card_uid: cardUid, idempotency_key: crypto.randomUUID() });
  expect(play.amount_minor).toBe(250);
  await readerPost(`/device/api/v1/plays/${play.id}/outcome`, { outcome: "unknown" });
  await page.goto("/plays");
  await page.getByRole("button", { name: "Resolve", exact: true }).click();
  await page.getByLabel("Confirmed outcome", { exact: true }).selectOption("refunded");
  await page.getByLabel("Evidence and reason", { exact: true }).fill("Operator checked the machine; no activation occurred.");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("row").filter({ hasText: play.id.slice(0, 12).toUpperCase() })).toContainText("refunded");
  const balance = await request.get(`/admin/api/v1/wallets/${walletId}/balance`, { headers });
  expect((await balance.json()).balance_minor).toBe(1000);
  await page.goto("/reports");
  await expect(page.getByRole("row").filter({ hasText: `Racer ${suffix}` })).toContainText("$0.00");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("machines-real-api.png"), fullPage: true });
  expect(errors).toEqual([]);
});
